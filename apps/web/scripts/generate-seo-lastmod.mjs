import { execFileSync } from "node:child_process"
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import matter from "gray-matter"

const scriptDir = dirname(fileURLToPath(import.meta.url))
const appRoot = resolve(scriptDir, "..")
const repoRoot = resolve(appRoot, "..", "..")
const contentRoot = join(appRoot, "content")
const outputFile = join(appRoot, "app", "seo", "lastmod.generated.ts")

function filesUnder(directory, extension) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) return filesUnder(path, extension)
    return entry.isFile() && path.endsWith(extension) ? [path] : []
  })
}

function routeForDoc(source) {
  const stem = relative(join(contentRoot, "docs"), source).replace(/\.mdx$/, "")
  return `/docs/${stem.replace(/\/index$/, "")}`
}

function readPost(source) {
  const { data } = matter(readFileSync(source, "utf8"))
  return {
    source,
    draft: data.draft === true,
    tags: Array.isArray(data.tags) ? data.tags.map((tag) => String(tag).toLowerCase()) : [],
  }
}

function lastCommitDate(sources, route) {
  const dates = sources.map((source) => {
    const relativeSource = relative(repoRoot, source)
    const output = execFileSync(
      "git",
      ["-C", repoRoot, "log", "-1", "--format=%cI", "--", relativeSource],
      {
        encoding: "utf8",
      },
    ).trim()
    const timestamp = Date.parse(output)
    if (!output || Number.isNaN(timestamp)) {
      throw new Error(`No usable Git history for ${route}: ${relativeSource}`)
    }
    return timestamp
  })

  if (dates.length === 0) throw new Error(`No substantive content sources for ${route}`)
  return new Date(Math.max(...dates)).toISOString()
}

const docs = filesUnder(join(contentRoot, "docs"), ".mdx")
const posts = filesUnder(join(contentRoot, "blog"), ".mdx").map(readPost)
const publishedPosts = posts.filter((post) => !post.draft)
const landingComponents = filesUnder(join(appRoot, "app", "components", "landing"), ".tsx")

const sourcesByRoute = new Map([
  ["/", [join(appRoot, "app", "page.tsx"), ...landingComponents]],
  ["/blog", publishedPosts.map((post) => post.source)],
  ...docs.map((source) => [routeForDoc(source), [source]]),
])

for (const tag of new Set(publishedPosts.flatMap((post) => post.tags))) {
  sourcesByRoute.set(
    `/blog/tags/${tag}`,
    publishedPosts.filter((post) => post.tags.includes(tag)).map((post) => post.source),
  )
}

const entries = [...sourcesByRoute.entries()]
  .map(([route, sources]) => [route, lastCommitDate(sources, route)])
  .sort(([left], [right]) => left.localeCompare(right))

const content = [
  "// Generated by scripts/generate-seo-lastmod.mjs. Do not edit by hand.",
  "export const STATIC_LASTMOD: Readonly<Record<string, string>> = {",
  ...entries.map(
    ([route, lastModified]) => `  ${JSON.stringify(route)}: ${JSON.stringify(lastModified)},`,
  ),
  "}",
  "",
].join("\n")

mkdirSync(dirname(outputFile), { recursive: true })
writeFileSync(outputFile, content)
