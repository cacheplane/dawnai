import { basename } from "node:path"

import {
  emitModulesFileWithFlavor,
  type ModulesEmitFlavor,
  type ModulesEmitOptions,
} from "./modules-emitter.js"

/**
 * Fallback namespace for the degenerate case where `basename(appRoot)` is
 * empty (an app root that is the filesystem root, or a bare separator). An
 * empty segment would still be opaque enough to work, but it makes every
 * derived key look truncated in logs and thread ids.
 */
const FALLBACK_APP_NAMESPACE = "app"

/**
 * The app's namespace on an edge runtime: its directory name, made
 * absolute-looking with a leading "/".
 *
 * Nothing resolves this onto a filesystem — it is an opaque id for thread and
 * cache keys. The leading slash is there because Dawn's pure path helpers
 * reject a RELATIVE base: `pureResolve` has no `process.cwd()` to fall back on,
 * so it throws rather than silently rooting a path somewhere. The generated
 * `app.mjs` hands this same value to `createRuntimeFetchHandler` as `appRoot`,
 * and built-in capabilities derive paths from it — `agents-md.ts` does
 * `pureResolve(appRoot, "workspace", "AGENTS.md")`, which is reached regardless
 * of the edge capability gating. A bare basename would throw there at runtime.
 *
 * Deliberately NOT the absolute build-machine path: a deployed bundle must not
 * depend on, or leak, where it was built.
 */
function edgeAppNamespace(appRoot: string): string {
  return `/${basename(appRoot) || FALLBACK_APP_NAMESPACE}`
}

/**
 * The edge flavor of the static manifest. It differs from the node manifest
 * (`emitModulesFile`) in exactly three ways, all forced by the runtime:
 *
 * 1. no `node:path` / `node:url` prelude — an edge runtime has neither module,
 *    so importing them is a boot-time link failure, not a graceful degradation;
 * 2. `appRoot` is a build-time string LITERAL rather than
 *    `resolve(dirname(fileURLToPath(import.meta.url)), "..", "..")`. There is no
 *    filesystem to resolve onto, so the value is only ever an opaque namespace
 *    id (thread keys, cache keys) — see {@link edgeAppNamespace} for why it is
 *    `/<app-dir-name>` and never the absolute build-machine path;
 * 3. `buildStaticRouteModule` / `normalizeMiddlewareModule` come from
 *    `@dawn-ai/cli/fetch` — the node-free entry — instead of
 *    `@dawn-ai/cli/runtime`, whose graph reaches tsx and sqlite.
 *
 * Consequently `routeFile` and tool `filePath`s are string concatenations onto
 * that literal rather than `resolve(appRoot, …)` calls: `resolve` would be a
 * free variable here. They are namespace ids of the same shape, not paths that
 * anything on the edge opens.
 */
const EDGE_FLAVOR: ModulesEmitFlavor = {
  // Interpolated through JSON.stringify like every other emitted value, so a
  // quote or backslash in a path component cannot terminate the literal early.
  appRootPathExpression: (relativePath) => `appRoot + ${JSON.stringify(`/${relativePath}`)}`,
  appRootSection: (appRoot) => [
    `// There is no filesystem and no import.meta.url path math on an edge runtime,`,
    `// so appRoot is a build-time literal: the app directory's name, used purely as`,
    `// an opaque namespace id (thread keys, cache keys). Never a build-machine path`,
    `// — a deployed bundle must not depend on where it was built. It is rooted at`,
    `// "/" because nothing resolves it on disk but Dawn's pure path helpers reject a`,
    `// relative base (pureResolve throws rather than rooting at a cwd that an edge`,
    `// runtime does not have).`,
    `const appRoot = ${JSON.stringify(edgeAppNamespace(appRoot))}`,
  ],
  header: [
    `// Generated by dawn build (hono target). Regenerated on every build — do not edit.`,
    `// Static module manifest for an edge bundle: every route/tool/memory/reducer`,
    `// module below is a static import, so the whole app module graph is known`,
    `// without filesystem discovery. Loaded by app.mjs as a plain ES module.`,
  ],
  preludeImports: [],
  runtimeSpecifier: "@dawn-ai/cli/fetch",
}

/**
 * Generate the text of `.dawn/build/modules.edge.mjs`.
 *
 * Shares its whole body with the node emitter ({@link emitModulesFileWithFlavor})
 * — the JSON.stringify'd import specifiers, the JSON.parse-encoded state
 * defaults and tool schemas (a quoted `"__proto__"` key in a bare object
 * literal performs a prototype assignment), and the build-time
 * JSON-round-trip guard on state defaults. Only the {@link EDGE_FLAVOR} lines
 * differ; a forked copy is how that hardening would silently stop applying to
 * the edge path.
 *
 * `appRoot` is the absolute app root on the BUILD machine, exactly as the node
 * emitter takes it: relative import specifiers are derived from it, and the
 * basename it bakes in is computed here rather than by the caller so no target
 * can accidentally emit a full path.
 */
export function emitEdgeModulesFile(options: ModulesEmitOptions): string {
  return emitModulesFileWithFlavor(options, EDGE_FLAVOR)
}
