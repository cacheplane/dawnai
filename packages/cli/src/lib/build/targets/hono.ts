import { existsSync } from "node:fs"
import { readFile, writeFile } from "node:fs/promises"
import { basename, join, resolve } from "node:path"

import type { DawnConfig } from "@dawn-ai/core"
import { providerPackages } from "@dawn-ai/langchain"
import type { BuiltInModelProviderId } from "@dawn-ai/sdk"

import { middlewareCandidatePaths } from "../../dev/middleware.js"
import { loadDawnConfig } from "../../node-config.js"
import { CliError, writeLine } from "../../output.js"
import { collectRouteProviders } from "../../runtime/collect-route-providers.js"
import { edgeAppNamespace, emitEdgeModulesFile } from "./edge-modules-emitter.js"
import type { BuildEmitContext, BuildTarget } from "./index.js"
import { collectRouteStaticDiscovery, type RouteStaticDiscovery } from "./modules-emitter.js"

/**
 * Compatibility date baked into the emitted `wrangler.toml`. A fixed date, not
 * "today": a worker's behavior must not change because it was rebuilt on a
 * different day. Bump it deliberately, with the runtime changes reviewed.
 */
const WRANGLER_COMPATIBILITY_DATE = "2026-08-01"

/**
 * Marker on the emitted `wrangler.toml`, matching the node target's Dockerfile
 * marker: it tells a human (and a future rebuild) which file Dawn authored.
 * Unlike the Dockerfile, this one is never overwritten — see {@link emitWrangler}.
 */
const WRANGLER_MARKER = "# Generated by dawn build (hono target)."

/**
 * The Hono/edge deploy target.
 *
 * Emits four artifacts into `.dawn/build/` (plus a `wrangler.toml` scaffold at
 * the app root):
 *
 * - `modules.edge.mjs` — the static module manifest, node-builtin-free;
 * - `stores.mjs` — a PER-REQUEST store factory (see its own header for why a
 *   module-scope pool is not an option on workerd);
 * - `app.mjs` — the Hono entry: one catch-all handing every request to
 *   `createRuntimeFetchHandler`, default-exported (the shape Workers, Vercel
 *   and Bun all accept);
 * - `wrangler.toml` — a scaffold, written only when the app has none.
 *
 * NOT in `DEFAULT_BUILD_TARGETS`: opt in with `build: { targets: [...] }`.
 */
export const honoTarget: BuildTarget = {
  name: "hono",
  async emit(ctx: BuildEmitContext) {
    const { appRoot, buildDir, io, manifest } = ctx
    const artifacts: string[] = []

    // The runtime's own discovery functions, run once here at build time —
    // identical to what the node target does, so the two manifests can only
    // ever disagree about the three lines the edge flavor changes.
    const discoveries: RouteStaticDiscovery[] = []
    for (const route of manifest.routes) {
      discoveries.push(await collectRouteStaticDiscovery({ appRoot, route }))
    }
    // Same candidate list, same precedence order, as the dynamic probe. The
    // manifest carries the result, and `createRuntimeFetchHandler` prefers
    // `modules.middleware` — which is how app.mjs mounts app middleware
    // without a filesystem probe it could not perform on the edge.
    const middlewareFile = middlewareCandidatePaths(appRoot).find((candidate) =>
      existsSync(candidate),
    )

    const modulesPath = join(buildDir, "modules.edge.mjs")
    await writeFile(
      modulesPath,
      emitEdgeModulesFile({
        appRoot,
        buildDir,
        discoveries,
        ...(middlewareFile ? { middlewareFile } : {}),
      }),
      "utf8",
    )
    artifacts.push(modulesPath)

    const storesPath = join(buildDir, "stores.mjs")
    await writeFile(storesPath, STORES_ENTRY, "utf8")
    artifacts.push(storesPath)

    const appPath = join(buildDir, "app.mjs")
    await writeFile(
      appPath,
      emitAppEntry({
        appRoot,
        config: await loadBuildConfig(appRoot),
        providers: await collectRouteProviders(manifest),
      }),
      "utf8",
    )
    artifacts.push(appPath)

    artifacts.push(await emitWrangler(ctx))

    return { artifacts }
  },
}

