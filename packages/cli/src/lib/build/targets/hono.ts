import { existsSync } from "node:fs"
import { readFile, writeFile } from "node:fs/promises"
import { basename, join, resolve } from "node:path"

import { writeLine } from "../../output.js"
import type { BuildEmitContext, BuildTarget } from "./index.js"
import { emitWebRuntimeArtifacts } from "./web-runtime.js"

/**
 * Compatibility date baked into the emitted `wrangler.toml`. A fixed date, not
 * "today": a worker's behavior must not change because it was rebuilt on a
 * different day. Bump it deliberately, with the runtime changes reviewed.
 */
const WRANGLER_COMPATIBILITY_DATE = "2026-08-01"

/**
 * Marker on the emitted `wrangler.toml`, matching the node target's Dockerfile
 * marker: it tells a human — and, via the read-back in {@link emitWrangler}, a
 * future rebuild — which file Dawn authored. Unlike the Dockerfile, a marked
 * file is still never OVERWRITTEN; the marker only stops the rebuild from
 * mistaking Dawn's own scaffold for a hand-written one.
 */
const WRANGLER_MARKER = "# Generated by dawn build (hono target)."

/**
 * The Hono/Cloudflare deploy target.
 *
 * Emits the shared web runtime into `.dawn/build/` plus a `wrangler.toml`
 * scaffold at the app root. NOT in `DEFAULT_BUILD_TARGETS`: opt in with
 * `build: { targets: [...] }`.
 */
export const honoTarget: BuildTarget = {
  name: "hono",
  async emit(ctx: BuildEmitContext) {
    const runtime = await emitWebRuntimeArtifacts(ctx, {
      outputDir: ctx.buildDir,
      targetName: "hono",
    })
    return {
      artifacts: [...runtime.artifacts, await emitWrangler(ctx)],
    }
  },
}

/**
 * Write the `wrangler.toml` scaffold — only when the app root has none.
 *
 * Three cases, and the middle one is the reason the marker is read back rather
 * than only written:
 *
 *   • no wrangler.toml at appRoot     → write ours there;
 *   • one carrying our marker         → OURS from a previous build. Leave it
 *     exactly as it is, say nothing, and keep reporting the app-root path;
 *   • one without the marker          → hand-written. Preserve it, emit ours
 *     into the build dir, and say so on stderr.
 *
 * Without the read-back every rebuild treated its own output as a stranger's:
 * a spurious ⚠, a redundant copy in `.dawn/build/`, and — quietest of the three
 * — the reported artifact path moving from the app root to the build dir, so
 * the file the operator actually deploys stopped being the one the build named.
 *
 * A marked file is still never OVERWRITTEN, deliberately unlike the node
 * target's Dockerfile: a `wrangler.toml` accretes bindings, vars and routes
 * that only the operator knows about, and clobbering them takes a deploy down.
 *
 * No `nodejs_compat`: the spike proved a bare name/main/compatibility_date boots
 * the handler, and adding the flag would mask a regression in the work that made
 * this bundle free of node builtins.
 */
async function emitWrangler(ctx: BuildEmitContext): Promise<string> {
  const { appRoot, buildDir, io } = ctx
  const appRootWrangler = resolve(appRoot, "wrangler.toml")

  // An unreadable existing file is treated as the user's, not as ours: the one
  // thing we must never do is claim authorship of something we could not read.
  const existing = existsSync(appRootWrangler)
    ? await readFile(appRootWrangler, "utf8").catch(() => "")
    : undefined
  if (existing?.includes(WRANGLER_MARKER)) return appRootWrangler

  const content = `${WRANGLER_MARKER} Dawn will not overwrite this file — it is yours to edit.
name = ${JSON.stringify(await workerName(appRoot))}
main = ".dawn/build/app.mjs"
compatibility_date = "${WRANGLER_COMPATIBILITY_DATE}"
`
  if (existing === undefined) {
    await writeFile(appRootWrangler, content, "utf8")
    return appRootWrangler
  }
  const buildDirWrangler = join(buildDir, "wrangler.toml")
  if (io) {
    writeLine(
      io.stderr,
      `⚠ Kept your existing ${appRootWrangler}; wrote the hono target's wrangler.toml to ${buildDirWrangler} instead.`,
    )
  }
  await writeFile(buildDirWrangler, content, "utf8")
  return buildDirWrangler
}

/**
 * The worker name: the app's package name, reduced to what Cloudflare accepts —
 * lowercase alphanumerics and dashes, STARTING WITH A LETTER. That last rule is
 * not cosmetic: a package named `123-app` otherwise emits a `wrangler.toml`
 * wrangler rejects outright, at deploy time, from a file the operator did not
 * write. Best-effort — the operator renames it in their own `wrangler.toml`,
 * which this never overwrites.
 */
async function workerName(appRoot: string): Promise<string> {
  let name = basename(appRoot)
  const packageJsonPath = resolve(appRoot, "package.json")
  if (existsSync(packageJsonPath)) {
    try {
      const parsed = JSON.parse(await readFile(packageJsonPath, "utf8")) as { name?: unknown }
      // Scoped names lose the scope: "@acme/support" → "support".
      if (typeof parsed.name === "string" && parsed.name)
        name = parsed.name.split("/").pop() ?? name
    } catch {
      // Unreadable/malformed package.json — fall back to the directory name.
    }
  }
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9-]+/g, "-")
      // Leading non-letters are dropped rather than prefixed: "123-app" reads
      // better as "app" than as "dawn-123-app", and a name that is ALL digits
      // falls through to the default below.
      .replace(/^[^a-z]+/, "")
      .replace(/-+$/, "") || "dawn-app"
  )
}
